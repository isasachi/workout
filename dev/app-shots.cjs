const { chromium } = require('playwright');
const out = process.argv[2];
const when = process.argv[3] || '2026-10-26T10:00:00';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  await p.clock.install({ time: new Date(when) });
  const errs = [];
  p.on('pageerror', (e) => errs.push('pageerror ' + e.message));
  p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  const shot = async (name, full = false) => { await p.waitForTimeout(900); await p.screenshot({ path: `${out}/${name}.png`, fullPage: full }); };
  await p.goto('http://localhost:5173/');
  await p.clock.runFor(500);
  await shot('01-start', true);
  await p.getByRole('button', { name: 'Hoy', exact: true }).first().click();
  await shot('02-today', true);
  await p.getByRole('button', { name: 'Empezar' }).click();
  await shot('03-warmup');
  await p.getByRole('button', { name: 'Empezar ejercicios' }).click();
  await shot('04-ex1');
  await p.getByRole('button', { name: /Marcar serie 1/ }).click();
  await shot('05-ex1-set', true);
  await p.getByRole('button', { name: 'Cerrar' }).click();
  await p.getByRole('button', { name: /Sentadilla libre/ }).first().click();
  await shot('06-sheet', true);
  await p.getByRole('button', { name: 'Cerrar' }).click();
  await p.getByRole('button', { name: 'Plan', exact: true }).click();
  await shot('07-plan', true);
  await p.getByRole('button', { name: 'Progreso', exact: true }).click();
  await shot('08-progress', true);
  console.log(errs.length ? 'ERRORS\n' + errs.join('\n') : 'no errors');
  await b.close();
})();
